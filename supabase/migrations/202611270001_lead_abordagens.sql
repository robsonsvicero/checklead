CREATE TABLE IF NOT EXISTS public.lead_abordagens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  lead_id integer NOT NULL,
  numero integer NOT NULL CHECK (numero >= 0),
  titulo text NOT NULL,
  canal text CHECK (canal IN ('whatsapp', 'email', 'telefone', 'instagram', 'outro')),
  mensagem text NOT NULL DEFAULT '',
  resultado text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'rascunho'
    CHECK (status IN ('rascunho', 'enviada', 'concluida')),
  criado_em timestamptz NOT NULL DEFAULT now(),
  atualizado_em timestamptz NOT NULL DEFAULT now(),
  UNIQUE (lead_id, numero),
  FOREIGN KEY (lead_id, user_id)
    REFERENCES public.leads(id, user_id)
    ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_lead_abordagens_user_lead_numero
  ON public.lead_abordagens(user_id, lead_id, numero);

ALTER TABLE public.lead_abordagens ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS lead_abordagens_own ON public.lead_abordagens;
CREATE POLICY lead_abordagens_own ON public.lead_abordagens
  FOR ALL TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());

GRANT SELECT, INSERT, UPDATE, DELETE ON public.lead_abordagens TO authenticated;
GRANT ALL ON public.lead_abordagens TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.lead_abordagens_id_seq TO authenticated, service_role;

INSERT INTO public.lead_abordagens (
  user_id, lead_id, numero, titulo, canal, mensagem, resultado, status
)
SELECT user_id, id, 0, 'Descobrir quem é o decisor', NULL, '', '', 'rascunho'
FROM public.leads
WHERE user_id IS NOT NULL
ON CONFLICT (lead_id, numero) DO NOTHING;

CREATE OR REPLACE FUNCTION public.restaurar_backup(p_user_id uuid, p_backup jsonb)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
  item jsonb;
  novo_id integer;
  id_antigo integer;
  total_interacoes integer := 0;
  total_abordagens integer := 0;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.perfis WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'Usuário inválido';
  END IF;
  IF jsonb_typeof(p_backup->'leads') <> 'array' THEN
    RAISE EXCEPTION 'Arquivo de backup inválido: lista de leads ausente';
  END IF;

  CREATE TEMP TABLE IF NOT EXISTS backup_lead_map (
    id_antigo integer PRIMARY KEY,
    id_novo integer NOT NULL
  ) ON COMMIT DROP;
  TRUNCATE pg_temp.backup_lead_map;

  DELETE FROM public.leads WHERE user_id = p_user_id;

  IF jsonb_typeof(p_backup->'configuracao') = 'object' THEN
    INSERT INTO public.configuracoes (
      user_id, limite_sem_resposta_horas, limite_follow_up_dias,
      limite_lead_parado_dias, atualizado_em
    )
    VALUES (
      p_user_id,
      coalesce((p_backup->'configuracao'->>'limite_sem_resposta_horas')::integer, 24),
      coalesce((p_backup->'configuracao'->>'limite_follow_up_dias')::integer, 3),
      coalesce((p_backup->'configuracao'->>'limite_lead_parado_dias')::integer, 7),
      now()
    )
    ON CONFLICT (user_id)
    DO UPDATE SET
      limite_sem_resposta_horas = EXCLUDED.limite_sem_resposta_horas,
      limite_follow_up_dias = EXCLUDED.limite_follow_up_dias,
      limite_lead_parado_dias = EXCLUDED.limite_lead_parado_dias,
      atualizado_em = EXCLUDED.atualizado_em;
  END IF;

  FOR item IN SELECT value FROM jsonb_array_elements(p_backup->'leads')
  LOOP
    INSERT INTO public.leads (
      user_id, nome, contato, whatsapp, email, responsavel, servico, origem,
      valor_estimado, status, criado_em, ultimo_contato_em,
      orcamento_enviado_em, fechado_em, motivo_perda, proxima_acao_em
    )
    VALUES (
      p_user_id, item->>'nome', item->>'contato', item->>'whatsapp', item->>'email',
      item->>'responsavel', item->>'servico', item->>'origem',
      coalesce((item->>'valor_estimado')::integer, 0),
      coalesce(item->>'status', 'novo'),
      coalesce(nullif(item->>'criado_em', '')::timestamptz, now()),
      nullif(item->>'ultimo_contato_em', '')::timestamptz,
      nullif(item->>'orcamento_enviado_em', '')::timestamptz,
      nullif(item->>'fechado_em', '')::timestamptz,
      item->>'motivo_perda',
      nullif(item->>'proxima_acao_em', '')::timestamptz
    )
    RETURNING id INTO novo_id;

    id_antigo := (item->>'id')::integer;
    INSERT INTO pg_temp.backup_lead_map (id_antigo, id_novo)
    VALUES (id_antigo, novo_id);
  END LOOP;

  IF jsonb_typeof(p_backup->'interacoes') = 'array' THEN
    FOR item IN SELECT value FROM jsonb_array_elements(p_backup->'interacoes')
    LOOP
      SELECT id_novo INTO novo_id
      FROM pg_temp.backup_lead_map
      WHERE id_antigo = (item->>'lead_id')::integer;

      IF NOT FOUND THEN
        RAISE EXCEPTION 'O backup contém uma interação sem lead correspondente';
      END IF;

      INSERT INTO public.interacoes (user_id, lead_id, tipo, texto, criado_em)
      VALUES (
        p_user_id,
        novo_id,
        item->>'tipo',
        item->>'texto',
        coalesce(nullif(item->>'criado_em', '')::timestamptz, now())
      );
      total_interacoes := total_interacoes + 1;
    END LOOP;
  END IF;

  IF jsonb_typeof(p_backup->'abordagens') = 'array' THEN
    FOR item IN SELECT value FROM jsonb_array_elements(p_backup->'abordagens')
    LOOP
      SELECT id_novo INTO novo_id
      FROM pg_temp.backup_lead_map
      WHERE id_antigo = (item->>'lead_id')::integer;

      IF NOT FOUND THEN
        RAISE EXCEPTION 'O backup contém uma abordagem sem lead correspondente';
      END IF;

      INSERT INTO public.lead_abordagens (
        user_id, lead_id, numero, titulo, canal, mensagem, resultado, status,
        criado_em, atualizado_em
      )
      VALUES (
        p_user_id,
        novo_id,
        coalesce((item->>'numero')::integer, 0),
        coalesce(item->>'titulo', 'Abordagem'),
        item->>'canal',
        coalesce(item->>'mensagem', ''),
        coalesce(item->>'resultado', ''),
        coalesce(item->>'status', 'rascunho'),
        coalesce(nullif(item->>'criado_em', '')::timestamptz, now()),
        coalesce(nullif(item->>'atualizado_em', '')::timestamptz, now())
      );
      total_abordagens := total_abordagens + 1;
    END LOOP;
  END IF;

  RETURN jsonb_build_object(
    'totalLeads', jsonb_array_length(p_backup->'leads'),
    'totalInteracoes', total_interacoes,
    'totalAbordagens', total_abordagens
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.migrar_backup_sqlite(p_user_id uuid, p_backup jsonb)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM public.perfis WHERE id = p_user_id) THEN
    RAISE EXCEPTION 'Crie a conta do usuário no Supabase Auth antes de migrar o SQLite';
  END IF;
  IF EXISTS (SELECT 1 FROM public.leads WHERE user_id = p_user_id)
     OR EXISTS (SELECT 1 FROM public.interacoes WHERE user_id = p_user_id) THEN
    RAISE EXCEPTION 'Migração cancelada: a conta de destino já possui leads ou interações';
  END IF;
  IF jsonb_typeof(p_backup->'leads') <> 'array'
     OR jsonb_typeof(p_backup->'interacoes') <> 'array' THEN
    RAISE EXCEPTION 'Payload da migração SQLite inválido';
  END IF;

  RETURN public.restaurar_backup(
    p_user_id,
    jsonb_build_object(
      'leads', p_backup->'leads',
      'interacoes', p_backup->'interacoes',
      'abordagens', coalesce(p_backup->'abordagens', '[]'::jsonb),
      'configuracao', p_backup->'configuracoes'
    )
  );
END;
$$;

REVOKE ALL ON FUNCTION public.restaurar_backup(uuid, jsonb) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.migrar_backup_sqlite(uuid, jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.restaurar_backup(uuid, jsonb) TO service_role;
GRANT EXECUTE ON FUNCTION public.migrar_backup_sqlite(uuid, jsonb) TO service_role;
