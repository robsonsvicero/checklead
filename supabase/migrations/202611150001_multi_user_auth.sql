CREATE TABLE IF NOT EXISTS public.perfis (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email text,
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
  criado_em timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_perfis_email_lower
  ON public.perfis (lower(email))
  WHERE email IS NOT NULL;

ALTER TABLE public.leads
  ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE RESTRICT;

ALTER TABLE public.interacoes
  ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE RESTRICT;

ALTER TABLE public.configuracoes
  ADD COLUMN IF NOT EXISTS user_id uuid REFERENCES auth.users(id) ON DELETE RESTRICT;

ALTER TABLE public.configuracoes
  DROP CONSTRAINT IF EXISTS configuracoes_id_check;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = 'public'
      AND table_name = 'configuracoes'
      AND column_name = 'id'
      AND is_identity = 'YES'
  ) THEN
    ALTER TABLE public.configuracoes
      ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
  END IF;
END
$$;

DO $$
DECLARE
  config_sequence text;
  config_max_id integer;
BEGIN
  config_sequence := pg_get_serial_sequence('public.configuracoes', 'id');
  IF config_sequence IS NOT NULL THEN
    SELECT coalesce(max(id), 0) INTO config_max_id FROM public.configuracoes;
    PERFORM setval(config_sequence, greatest(config_max_id, 1), config_max_id > 0);
  END IF;
END
$$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_configuracoes_user_id
  ON public.configuracoes (user_id);

CREATE INDEX IF NOT EXISTS idx_leads_user_id ON public.leads(user_id);
CREATE INDEX IF NOT EXISTS idx_interacoes_user_id ON public.interacoes(user_id);

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'leads_id_user_id_key'
  ) THEN
    ALTER TABLE public.leads
      ADD CONSTRAINT leads_id_user_id_key UNIQUE (id, user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'interacoes_lead_user_id_fkey'
  ) THEN
    ALTER TABLE public.interacoes
      ADD CONSTRAINT interacoes_lead_user_id_fkey
      FOREIGN KEY (lead_id, user_id)
      REFERENCES public.leads(id, user_id)
      ON DELETE CASCADE;
  END IF;
END
$$;

INSERT INTO public.perfis (id, email, role, criado_em)
SELECT id, lower(email), 'user', created_at
FROM auth.users
ON CONFLICT (id) DO UPDATE
SET email = EXCLUDED.email;

INSERT INTO public.configuracoes (
  limite_sem_resposta_horas,
  limite_follow_up_dias,
  limite_lead_parado_dias,
  atualizado_em,
  user_id
)
SELECT 24, 3, 7, now(), p.id
FROM public.perfis AS p
WHERE NOT EXISTS (
  SELECT 1 FROM public.configuracoes AS c WHERE c.user_id = p.id
);

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  INSERT INTO public.perfis (id, email, role, criado_em)
  VALUES (NEW.id, lower(NEW.email), 'user', coalesce(NEW.created_at, now()))
  ON CONFLICT (id) DO UPDATE SET email = EXCLUDED.email;

  INSERT INTO public.configuracoes (
    limite_sem_resposta_horas,
    limite_follow_up_dias,
    limite_lead_parado_dias,
    atualizado_em,
    user_id
  )
  VALUES (24, 3, 7, now(), NEW.id)
  ON CONFLICT (user_id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_auth_user();
REVOKE ALL ON FUNCTION public.handle_new_auth_user() FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.handle_auth_user_email_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  UPDATE public.perfis
  SET email = lower(NEW.email)
  WHERE id = NEW.id;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_email_updated ON auth.users;
CREATE TRIGGER on_auth_user_email_updated
  AFTER UPDATE OF email ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_auth_user_email_update();
REVOKE ALL ON FUNCTION public.handle_auth_user_email_update() FROM PUBLIC, anon, authenticated;

