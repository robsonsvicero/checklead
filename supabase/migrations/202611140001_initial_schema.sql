CREATE TABLE IF NOT EXISTS public.usuarios (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  senha_hash text NOT NULL,
  criado_em text NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_usuarios_singleton ON public.usuarios ((true));

CREATE TABLE IF NOT EXISTS public.configuracoes (
  id integer PRIMARY KEY CHECK (id = 1),
  limite_sem_resposta_horas integer NOT NULL DEFAULT 24,
  limite_follow_up_dias integer NOT NULL DEFAULT 3,
  limite_lead_parado_dias integer NOT NULL DEFAULT 7,
  atualizado_em timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS public.leads (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  contato text NOT NULL,
  whatsapp text,
  email text,
  responsavel text,
  servico text NOT NULL,
  origem text NOT NULL,
  valor_estimado integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'novo'
    CHECK (status IN ('novo', 'orcamento_enviado', 'fechado', 'perdido')),
  criado_em timestamptz NOT NULL,
  ultimo_contato_em timestamptz,
  orcamento_enviado_em timestamptz,
  fechado_em timestamptz,
  motivo_perda text,
  proxima_acao_em timestamptz
);

CREATE INDEX IF NOT EXISTS idx_leads_status ON public.leads(status);
CREATE INDEX IF NOT EXISTS idx_leads_criado_em ON public.leads(criado_em);
CREATE INDEX IF NOT EXISTS idx_leads_nome ON public.leads(nome);

CREATE TABLE IF NOT EXISTS public.interacoes (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id integer NOT NULL REFERENCES public.leads(id) ON DELETE CASCADE,
  tipo text NOT NULL,
  texto text NOT NULL,
  criado_em timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_interacoes_lead_id ON public.interacoes(lead_id);
CREATE INDEX IF NOT EXISTS idx_interacoes_criado_em ON public.interacoes(criado_em);

ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.configuracoes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.interacoes ENABLE ROW LEVEL SECURITY;

INSERT INTO public.configuracoes (id, atualizado_em)
VALUES (1, now())
ON CONFLICT (id) DO NOTHING;

CREATE OR REPLACE FUNCTION public.criar_lead_atomic(p_lead jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  novo_lead public.leads%ROWTYPE;
  agora timestamptz := now();
  whatsapp_limpo text := nullif(btrim(p_lead->>'whatsapp'), '');
  email_limpo text := nullif(btrim(p_lead->>'email'), '');
  responsavel_limpo text := nullif(btrim(p_lead->>'responsavel'), '');
BEGIN
  INSERT INTO public.leads (
    nome, contato, whatsapp, email, responsavel, servico, origem,
    valor_estimado, status, criado_em, proxima_acao_em
  ) VALUES (
    btrim(p_lead->>'nome'),
    coalesce(nullif(btrim(p_lead->>'contato'), ''), whatsapp_limpo, email_limpo, 'Sem contato'),
    whatsapp_limpo,
    email_limpo,
    responsavel_limpo,
    btrim(p_lead->>'servico'),
    p_lead->>'origem',
    coalesce((p_lead->>'valor_estimado')::integer, 0),
    'novo',
    agora,
    nullif(p_lead->>'proxima_acao_em', '')::timestamptz
  )
  RETURNING * INTO novo_lead;

  INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
  VALUES (
    novo_lead.id,
    'nota',
    format(
      'Lead criado no Radar via %s. Responsável: %s. Serviço: %s.',
      novo_lead.origem,
      coalesce(responsavel_limpo, 'Não definido'),
      novo_lead.servico
    ),
    agora
  );

  RETURN to_jsonb(novo_lead);
END;
$$;

CREATE OR REPLACE FUNCTION public.executar_acao_lead(p_id integer, p_acao jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  lead_atual public.leads%ROWTYPE;
  agora timestamptz := now();
  tipo_acao text := p_acao->>'tipo';
  texto_acao text := nullif(p_acao->>'texto', '');
BEGIN
  SELECT * INTO lead_atual
  FROM public.leads
  WHERE id = p_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Lead não encontrado';
  END IF;

  CASE tipo_acao
    WHEN 'contato' THEN
      UPDATE public.leads SET ultimo_contato_em = agora WHERE id = p_id;
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (p_id, 'contato', coalesce(texto_acao, 'Contato realizado com o cliente.'), agora);
    WHEN 'orcamento' THEN
      UPDATE public.leads
      SET status = 'orcamento_enviado', orcamento_enviado_em = agora, ultimo_contato_em = agora
      WHERE id = p_id;
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (p_id, 'orcamento', coalesce(texto_acao, 'Orçamento enviado com sucesso.'), agora);
    WHEN 'follow_up' THEN
      UPDATE public.leads SET ultimo_contato_em = agora WHERE id = p_id;
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (p_id, 'follow_up', coalesce(texto_acao, 'Follow-up de cobrança ou acompanhamento realizado.'), agora);
    WHEN 'fechou' THEN
      UPDATE public.leads SET status = 'fechado', fechado_em = agora, ultimo_contato_em = agora WHERE id = p_id;
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (p_id, 'contato', coalesce(texto_acao, 'Venda concluída! Lead marcado como fechado.'), agora);
    WHEN 'perdeu' THEN
      UPDATE public.leads
      SET status = 'perdido', fechado_em = agora, motivo_perda = p_acao->>'motivo_perda'
      WHERE id = p_id;
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (
        p_id,
        'nota',
        coalesce(texto_acao, format('Venda perdida. Motivo: %s', p_acao->>'motivo_perda')),
        agora
      );
    WHEN 'nota' THEN
      INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
      VALUES (p_id, 'nota', p_acao->>'texto', agora);
    ELSE
      RAISE EXCEPTION 'Ação de lead inválida';
  END CASE;

  SELECT * INTO lead_atual FROM public.leads WHERE id = p_id;

  RETURN jsonb_build_object(
    'lead', to_jsonb(lead_atual),
    'interacoes', coalesce(
      (SELECT jsonb_agg(to_jsonb(i) ORDER BY i.criado_em DESC, i.id DESC)
       FROM public.interacoes i WHERE i.lead_id = p_id),
      '[]'::jsonb
    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.importar_leads_em_lote(p_leads jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  item jsonb;
  novo_lead public.leads%ROWTYPE;
  agora timestamptz := now();
  total integer := 0;
BEGIN
  IF jsonb_typeof(p_leads) <> 'array' THEN
    RAISE EXCEPTION 'A lista de leads deve ser um array';
  END IF;

  FOR item IN SELECT value FROM jsonb_array_elements(p_leads)
  LOOP
    INSERT INTO public.leads (
      nome, contato, whatsapp, email, responsavel, servico, origem,
      valor_estimado, status, criado_em, orcamento_enviado_em,
      fechado_em, motivo_perda
    ) VALUES (
      btrim(item->>'nome'),
      coalesce(nullif(btrim(item->>'contato'), ''), nullif(btrim(item->>'whatsapp'), ''), nullif(btrim(item->>'email'), ''), 'Sem contato'),
      nullif(btrim(item->>'whatsapp'), ''),
      nullif(btrim(item->>'email'), ''),
      nullif(btrim(item->>'responsavel'), ''),
      coalesce(nullif(btrim(item->>'servico'), ''), 'Não especificado'),
      coalesce(item->>'origem', 'outro'),
      coalesce((item->>'valor_estimado')::integer, 0),
      coalesce(item->>'status', 'novo'),
      coalesce(nullif(item->>'criado_em', '')::timestamptz, agora),
      nullif(item->>'orcamento_enviado_em', '')::timestamptz,
      nullif(item->>'fechado_em', '')::timestamptz,
      nullif(item->>'motivo_perda', '')
    )
    RETURNING * INTO novo_lead;

    INSERT INTO public.interacoes (lead_id, tipo, texto, criado_em)
    VALUES (
      novo_lead.id,
      'nota',
      format(
        'Lead importado via planilha CSV. Origem: %s. Responsável: %s.',
        novo_lead.origem,
        coalesce(novo_lead.responsavel, 'Não informado')
      ),
      agora
    );
    total := total + 1;
  END LOOP;

  RETURN jsonb_build_object('totalImportados', total, 'totalIgnorados', 0);
END;
$$;

CREATE OR REPLACE FUNCTION public.restaurar_backup(p_backup jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  total_interacoes integer := 0;
BEGIN
  IF jsonb_typeof(p_backup->'leads') <> 'array' THEN
    RAISE EXCEPTION 'Arquivo de backup inválido: lista de leads ausente';
  END IF;

  DELETE FROM public.interacoes;
  DELETE FROM public.leads;

  IF jsonb_typeof(p_backup->'configuracao') = 'object' THEN
    UPDATE public.configuracoes
    SET limite_sem_resposta_horas = coalesce((p_backup->'configuracao'->>'limite_sem_resposta_horas')::integer, 24),
        limite_follow_up_dias = coalesce((p_backup->'configuracao'->>'limite_follow_up_dias')::integer, 3),
        limite_lead_parado_dias = coalesce((p_backup->'configuracao'->>'limite_lead_parado_dias')::integer, 7),
        atualizado_em = now()
    WHERE id = 1;
  END IF;

  INSERT INTO public.leads (
    id, nome, contato, whatsapp, email, responsavel, servico, origem,
    valor_estimado, status, criado_em, ultimo_contato_em,
    orcamento_enviado_em, fechado_em, motivo_perda, proxima_acao_em
  )
  SELECT
    item.id, item.nome, item.contato, item.whatsapp, item.email, item.responsavel,
    item.servico, item.origem, coalesce(item.valor_estimado, 0), coalesce(item.status, 'novo'),
    item.criado_em, item.ultimo_contato_em, item.orcamento_enviado_em, item.fechado_em,
    item.motivo_perda, item.proxima_acao_em
  FROM jsonb_to_recordset(p_backup->'leads') AS item(
    id integer, nome text, contato text, whatsapp text, email text, responsavel text,
    servico text, origem text, valor_estimado integer, status text, criado_em timestamptz,
    ultimo_contato_em timestamptz, orcamento_enviado_em timestamptz, fechado_em timestamptz,
    motivo_perda text, proxima_acao_em timestamptz
  );

  IF jsonb_typeof(p_backup->'interacoes') = 'array' THEN
    INSERT INTO public.interacoes (id, lead_id, tipo, texto, criado_em)
    SELECT item.id, item.lead_id, item.tipo, item.texto, item.criado_em
    FROM jsonb_to_recordset(p_backup->'interacoes') AS item(
      id integer, lead_id integer, tipo text, texto text, criado_em timestamptz
    );
    GET DIAGNOSTICS total_interacoes = ROW_COUNT;
  END IF;

  PERFORM setval(
    pg_get_serial_sequence('public.leads', 'id'),
    coalesce((SELECT max(id) FROM public.leads), 1),
    EXISTS (SELECT 1 FROM public.leads)
  );
  PERFORM setval(
    pg_get_serial_sequence('public.interacoes', 'id'),
    coalesce((SELECT max(id) FROM public.interacoes), 1),
    EXISTS (SELECT 1 FROM public.interacoes)
  );

  RETURN jsonb_build_object(
    'totalLeads', jsonb_array_length(p_backup->'leads'),
    'totalInteracoes', total_interacoes
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.migrar_backup_sqlite(p_backup jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  total_leads integer;
  total_interacoes integer := 0;
BEGIN
  IF EXISTS (SELECT 1 FROM public.leads)
     OR EXISTS (SELECT 1 FROM public.interacoes)
     OR EXISTS (SELECT 1 FROM public.usuarios) THEN
    RAISE EXCEPTION 'Migração cancelada: o Supabase já contém leads, interações ou usuário';
  END IF;

  IF jsonb_typeof(p_backup->'leads') <> 'array'
     OR jsonb_typeof(p_backup->'interacoes') <> 'array'
     OR jsonb_typeof(p_backup->'usuarios') <> 'array' THEN
    RAISE EXCEPTION 'Payload da migração SQLite inválido';
  END IF;

  INSERT INTO public.usuarios (id, senha_hash, criado_em)
  SELECT item.id, item.senha_hash, item.criado_em
  FROM jsonb_to_recordset(p_backup->'usuarios') AS item(
    id integer, senha_hash text, criado_em text
  );

  IF jsonb_typeof(p_backup->'configuracoes') = 'object' THEN
    UPDATE public.configuracoes
    SET limite_sem_resposta_horas = coalesce((p_backup->'configuracoes'->>'limite_sem_resposta_horas')::integer, 24),
        limite_follow_up_dias = coalesce((p_backup->'configuracoes'->>'limite_follow_up_dias')::integer, 3),
        limite_lead_parado_dias = coalesce((p_backup->'configuracoes'->>'limite_lead_parado_dias')::integer, 7),
        atualizado_em = now()
    WHERE id = 1;
  END IF;

  INSERT INTO public.leads (
    id, nome, contato, whatsapp, email, responsavel, servico, origem,
    valor_estimado, status, criado_em, ultimo_contato_em,
    orcamento_enviado_em, fechado_em, motivo_perda, proxima_acao_em
  )
  SELECT
    item.id, item.nome, item.contato, item.whatsapp, item.email, item.responsavel,
    item.servico, item.origem, coalesce(item.valor_estimado, 0), coalesce(item.status, 'novo'),
    item.criado_em, item.ultimo_contato_em, item.orcamento_enviado_em, item.fechado_em,
    item.motivo_perda, item.proxima_acao_em
  FROM jsonb_to_recordset(p_backup->'leads') AS item(
    id integer, nome text, contato text, whatsapp text, email text, responsavel text,
    servico text, origem text, valor_estimado integer, status text, criado_em timestamptz,
    ultimo_contato_em timestamptz, orcamento_enviado_em timestamptz, fechado_em timestamptz,
    motivo_perda text, proxima_acao_em timestamptz
  );
  GET DIAGNOSTICS total_leads = ROW_COUNT;

  INSERT INTO public.interacoes (id, lead_id, tipo, texto, criado_em)
  SELECT item.id, item.lead_id, item.tipo, item.texto, item.criado_em
  FROM jsonb_to_recordset(p_backup->'interacoes') AS item(
    id integer, lead_id integer, tipo text, texto text, criado_em timestamptz
  );
  GET DIAGNOSTICS total_interacoes = ROW_COUNT;

  PERFORM setval(
    pg_get_serial_sequence('public.usuarios', 'id'),
    coalesce((SELECT max(id) FROM public.usuarios), 1),
    EXISTS (SELECT 1 FROM public.usuarios)
  );
  PERFORM setval(
    pg_get_serial_sequence('public.leads', 'id'),
    coalesce((SELECT max(id) FROM public.leads), 1),
    EXISTS (SELECT 1 FROM public.leads)
  );
  PERFORM setval(
    pg_get_serial_sequence('public.interacoes', 'id'),
    coalesce((SELECT max(id) FROM public.interacoes), 1),
    EXISTS (SELECT 1 FROM public.interacoes)
  );

  RETURN jsonb_build_object(
    'totalLeads', total_leads,
    'totalInteracoes', total_interacoes
  );
END;
$$;

